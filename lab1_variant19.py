"""Лабораторная работа № 1. Вариант 19. Ситникова Ольга Алексеевна, группа БИ2-1.
Итерационные методы вычисления √a, ∛b и ln c.

Исходные данные варианта 19: a = 53, b = 300, c = 6, точность eps = 1e-4,
критерий остановки для корней — по невязке (|x² − a| < eps и |x³ − b| < eps), начальное приближение x0 = a (b),
дополнительное требование Д1 — таблица итераций с анализом числа верных знаков.

Как устроена программа (удобно для рассказа на защите):
  1. sqrt_newton — квадратный корень методом Ньютона (формула Герона).
  2. cbrt_newton — кубический корень методом Ньютона (с учётом знака числа).
  3. ln_series — натуральный логарифм через ряд по степеням y = (c − 1) / (c + 1).
  4. Каждая функция возвращает пару (результат, число итераций) и умеет по запросу записывать ход итераций (trace) —
     это нужно для таблицы Д1.
  5. Главная часть (внизу): считает три значения, сравнивает с эталоном из модуля math (только там!),
     печатает таблицы итераций Д1 и строит график скорости сходимости.

Важно: комментарии в Python начинаются с символа #, а не с //  (две косые черты в Python — это целочисленное деление).
Каждая строка кода ниже имеет пояснение в строке над ней.
"""
# Модуль math используется ТОЛЬКО в главной части — для эталонных значений и подсчёта верных знаков.
# Внутри вычислительных функций math.sqrt, math.log и степень **0.5 не применяются (требование задания).
import math
# Модуль platform нужен, чтобы напечатать сведения о компьютере и версии Python (для условий в отчёте).
import platform
# Библиотека matplotlib строит графики; plt — короткое имя для неё.
import matplotlib.pyplot as plt

# Исходные данные варианта 19: a — число под квадратным корнем, b — под кубическим корнем, c — аргумент логарифма.
A, B, C = 53, 300, 6
# EPS — требуемая точность (10 в степени минус 4); N_MAX — страховка: максимум итераций, чтобы не зациклиться.
EPS, N_MAX = 1e-4, 100


# Функция вычисляет квадратный корень числа a методом Ньютона (формула Герона).
# Возвращает пару: (найденное значение, число выполненных итераций).
# trace — необязательный список: если он передан, в него записывается ход итераций (для таблицы Д1).
def sqrt_newton(a, eps=EPS, n_max=N_MAX, trace=None):
    # Корень из отрицательного числа в вещественных числах не существует — сообщаем об ошибке.
    if a < 0:
        # Исключение ValueError с понятным сообщением прервёт работу функции.
        raise ValueError("Подкоренное выражение должно быть неотрицательным")
    # Корень из нуля равен нулю, итераций не требуется.
    if a == 0:
        # Возвращаем пару «результат, число итераций».
        return 0.0, 0
    # Начальное приближение x0 = a (так задано вариантом 19).
    x = a
    # Повторяем уточнение не более n_max раз; n — номер текущей итерации (1, 2, 3, …).
    for n in range(1, n_max + 1):
        # Формула Герона: новое приближение — среднее арифметическое x и a / x.
        x_new = 0.5 * (x + a / x)
        # Если нужно записать ход итераций…
        if trace is not None:
            # …добавляем строку: номер шага, новое приближение и его отличие от предыдущего.
            trace.append((n, x_new, abs(x_new - x)))
        # Критерий остановки «по невязке»: квадрат приближения должен отличаться от a меньше чем на eps.
        if abs(x_new * x_new - a) < eps:
            # Точность достигнута — возвращаем результат и число итераций.
            return x_new, n
        # Иначе принимаем новое приближение за текущее и идём на следующий шаг.
        x = x_new
    # Если цикл закончился, а точность не достигнута — сообщаем об ошибке (сработала страховка n_max).
    raise RuntimeError("Точность не достигнута за N_MAX итераций")


# Функция вычисляет кубический корень числа b методом Ньютона; для отрицательных b учитывает знак.
# Возвращает пару: (найденное значение, число выполненных итераций).
def cbrt_newton(b, eps=EPS, n_max=N_MAX, trace=None):
    # Кубический корень из нуля равен нулю.
    if b == 0:
        # Итераций не требуется.
        return 0.0, 0
    # Запоминаем знак числа: для отрицательного b корень отрицателен (∛(−8) = −2).
    sign = -1 if b < 0 else 1
    # Дальше работаем с модулем числа, а знак вернём в самом конце.
    b = abs(b)
    # Начальное приближение x0 = b (так задано вариантом 19: x0 равно самому аргументу).
    x = b
    # Повторяем уточнение не более n_max раз.
    for n in range(1, n_max + 1):
        # Формула Ньютона для кубического корня: (2x + b / x²) / 3.
        x_new = (2 * x + b / (x * x)) / 3
        # Если нужно записать ход итераций…
        if trace is not None:
            # …добавляем строку: номер шага, новое приближение и его отличие от предыдущего.
            trace.append((n, x_new, abs(x_new - x)))
        # Критерий остановки «по невязке»: куб приближения должен отличаться от b меньше чем на eps.
        if abs(x_new * x_new * x_new - b) < eps:
            # Точность достигнута — возвращаем результат (с восстановленным знаком) и число итераций.
            return sign * x_new, n
        # Иначе принимаем новое приближение за текущее.
        x = x_new
    # Страховка: точность не достигнута за n_max итераций.
    raise RuntimeError("Точность не достигнута за N_MAX итераций")


# Функция вычисляет натуральный логарифм ln c через ряд ln c = 2·(y + y³/3 + y⁵/5 + …), где y = (c − 1) / (c + 1).
# Для логарифма критерий остановки всегда один: модуль очередного члена ряда меньше eps.
# Возвращает пару: (найденное значение, число сложенных членов ряда).
def ln_series(c, eps=EPS, n_max=10_000, trace=None):
    # Логарифм определён только для положительных чисел.
    if c <= 0:
        # Сообщаем об ошибке.
        raise ValueError("Аргумент логарифма должен быть положительным")
    # Вспомогательная величина y: при любом c > 0 выполняется |y| < 1, поэтому ряд сходится.
    y = (c - 1) / (c + 1)
    # Квадрат y: на него умножаем степень при переходе к следующему члену ряда.
    y2 = y * y
    # power — текущая нечётная степень y (сначала y в первой степени).
    power = y
    # total — накопленная сумма ряда (сначала ноль).
    total = 0.0
    # Перебираем члены ряда; k — номер члена, начиная с нуля.
    for k in range(n_max):
        # k-й член ряда: 2 · y^(2k+1) / (2k+1).
        term = 2 * power / (2 * k + 1)
        # Если член стал по модулю меньше eps, то ряд можно прекращать суммировать.
        if abs(term) < eps:
            # Возвращаем сумму и число уже сложенных членов (k).
            return total, k
        # Иначе прибавляем член к сумме.
        total += term
        # Если нужно записать ход итераций…
        if trace is not None:
            # …добавляем строку: сколько членов сложено, текущая сумма и последний добавленный член.
            trace.append((k + 1, total, abs(term)))
        # Готовим следующую степень: умножаем на y², получаем y^(2k+3).
        power *= y2
    # Страховка: точность не достигнута за n_max членов.
    raise RuntimeError("Точность не достигнута за n_max итераций")


# Функция correct_digits считает, сколько верных десятичных знаков у приближения, зная погрешность err.
def correct_digits(err):
    # Если погрешность равна нулю (в пределах точности чисел float), верны все знаки — условно возвращаем 16.
    if err == 0:
        # Число 16 — это примерно столько десятичных знаков помещается в тип float.
        return 16
    # Число верных знаков — это целая часть от «минус десятичный логарифм погрешности», но не меньше нуля.
    return max(0, math.floor(-math.log10(err)))


# Функция show_table печатает таблицу итераций Д1 для одной функции.
# name — название, x0 — начальное значение, rows — записанный ход итераций, ref — эталонное значение,
# resid — функция невязки (или None), если невязку показывать не нужно.
def show_table(name, x0, rows, ref, resid):
    # Заголовок таблицы с названием функции и эталонным значением (перевод строки \n даёт пустую строку перед заголовком).
    print(f"\nТаблица итераций Д1: {name} (эталон {ref:.10f})")
    # Заголовок столбцов: номер шага, приближение, разность соседних приближений, невязка, погрешность, верные знаки.
    print(f"{'n':>3} {'x_n':>16} {'|x_n - x_(n-1)|':>16} {'невязка':>12} {'погрешность':>13} {'верных знаков':>14}")
    # Нулевая строка — начальное приближение (разности и верных знаков для него не считаем).
    print(f"{0:>3} {x0:>16.8f} {'—':>16} {'—':>12} {abs(x0 - ref):>13.3e} {correct_digits(abs(x0 - ref)):>14}")
    # Перебираем записанные шаги: n — номер, x — приближение, diff — разность с предыдущим приближением.
    for n, x, diff in rows:
        # Невязка считается только если передана функция resid; иначе ставим прочерк.
        r = f"{abs(resid(x)):>12.3e}" if resid else f"{'—':>12}"
        # Погрешность — это отличие приближения от эталона.
        err = abs(x - ref)
        # Печатаем строку таблицы.
        print(f"{n:>3} {x:>16.8f} {diff:>16.3e} {r} {err:>13.3e} {correct_digits(err):>14}")


# Следующий блок выполняется, только если файл запущен напрямую (а не подключён как модуль).
if __name__ == "__main__":
    # Печатаем сведения о системе и версии Python.
    print(platform.platform(), "|", platform.processor() or platform.machine(), "| Python", platform.python_version())
    # Эталонные значения из стандартной библиотеки (math разрешён только здесь): √a, ∛b и ln c.
    ref_sqrt, ref_cbrt, ref_ln = math.sqrt(A), B ** (1 / 3), math.log(C)
    # Списки, в которые функции запишут ход итераций (для таблиц Д1 и графика).
    tr_sqrt, tr_cbrt, tr_ln = [], [], []
    # Вычисляем три значения; каждая функция возвращает пару (результат, число итераций).
    v_sqrt, n_sqrt = sqrt_newton(A, trace=tr_sqrt)
    # Кубический корень из 300.
    v_cbrt, n_cbrt = cbrt_newton(B, trace=tr_cbrt)
    # Натуральный логарифм числа 6.
    v_ln, n_ln = ln_series(C, trace=tr_ln)
    # Заголовок итоговой таблицы результатов.
    print(f"\nРезультаты (eps = {EPS}):")
    # Заголовок столбцов итоговой таблицы.
    print(f"{'Функция':<10}{'Аргумент':>10}{'Результат':>16}{'Эталон':>16}{'Погрешность':>14}{'Итераций':>10}")
    # Перебираем три функции: название, аргумент, результат, эталон и число итераций.
    for name, arg, val, ref, n in (("sqrt", A, v_sqrt, ref_sqrt, n_sqrt), ("cbrt", B, v_cbrt, ref_cbrt, n_cbrt), ("ln", C, v_ln, ref_ln, n_ln)):
        # Печатаем строку: результат и эталон с 10 знаками, абсолютная погрешность в экспоненциальной форме.
        print(f"{name:<10}{arg:>10}{val:>16.10f}{ref:>16.10f}{abs(val - ref):>14.2e}{n:>10}")
    # Таблица Д1 для квадратного корня: x0 = a = 53, невязка = x² − a.
    show_table("√a, a = 53", A, tr_sqrt, ref_sqrt, lambda x: x * x - A)
    # Таблица Д1 для кубического корня: x0 = b = 300, невязка = x³ − b.
    show_table("∛b, b = 300", B, tr_cbrt, ref_cbrt, lambda x: x * x * x - B)
    # Таблица Д1 для логарифма: вместо x0 берём 0 (сумма ряда пока пуста), невязки у ряда нет.
    show_table("ln c, c = 6", 0.0, tr_ln, ref_ln, None)
    # Проверка защиты от некорректных данных: отрицательное подкоренное выражение и неположительный аргумент логарифма.
    for bad in (lambda: sqrt_newton(-4), lambda: ln_series(0)):
        # Пробуем выполнить вызов и перехватываем ожидаемую ошибку.
        try:
            # Вызов должен завершиться исключением ValueError.
            bad()
        # Если ошибка возникла — печатаем её текст (программа при этом не падает).
        except ValueError as e:
            # Сообщение об ошибке для пользователя.
            print("Проверка входных данных:", e)
    # Создаём график: по оси X — номер итерации, по оси Y — погрешность (логарифмическая шкала).
    fig, ax = plt.subplots(figsize=(8, 5))
    # Для каждой функции берём записанный ход итераций и эталон.
    for label, rows, ref in (("√a (Ньютон)", tr_sqrt, ref_sqrt), ("∛b (Ньютон)", tr_cbrt, ref_cbrt), ("ln c (ряд)", tr_ln, ref_ln)):
        # Рисуем погрешность |x_n − эталон| в зависимости от номера итерации; "o-" — точки, соединённые линией.
        ax.plot([r[0] for r in rows], [max(abs(r[1] - ref), 1e-17) for r in rows], "o-", label=label)
    # Горизонтальная красная пунктирная линия — требуемая точность eps.
    ax.axhline(EPS, color="red", linestyle="--", label="eps = 1e-4")
    # Подписи осей, заголовок и логарифмическая шкала по вертикали.
    ax.set(xlabel="Номер итерации n", ylabel="Погрешность |x_n − эталон|", title="Скорость сходимости (вариант 19)", yscale="log")
    # Сетка и легенда.
    ax.grid(True, alpha=0.3, which="both")
    # Легенда с названиями линий.
    ax.legend()
    # Автоматически расставляем элементы так, чтобы подписи не накладывались.
    plt.tight_layout()
    # Сохраняем график в файл lab1_graphs.png (он нужен для отчёта).
    plt.savefig("lab1_graphs.png", dpi=150)
    # Показываем график на экране.
    plt.show()
